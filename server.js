/* ---- helpers ---- */
const newId = () => "s_" + Math.random().toString(36).slice(2, 10) + Date.now().toString(36).slice(-4);
const clientOf = (req) => String(req.get("X-Client-Id") || req.ip || "anon").slice(0, 64);
function clean(str, max) {
  return String(str == null ? "" : str).replace(/[\u0000-\u001f\u007f]/g, "").trim().slice(0, max);
}
function rowToPublic(row, liked) {
  return {
    id: row.id, name: row.name, author: row.author, lang: row.lang,
    code: row.code, uses: row.uses, likes: row.likes,
    createdAt: row.created_at, liked: !!liked,
  };
}

/* ---- app ---- */
const app = express();
app.set("trust proxy", 1); // behind nginx/caddy
app.use(express.json({ limit: "128kb" })); // room create/join carry a small avatar data URL
app.use(cors({
  origin: ORIGINS.includes("*") ? true : ORIGINS,
  methods: ["GET", "POST"],
  allowedHeaders: ["Content-Type", "X-Client-Id"],
}));

const writeLimiter = rateLimit({
  windowMs: 60 * 1000,
  max: 20,                       // 20 writes/min per IP
  standardHeaders: true,
  legacyHeaders: false,
  message: { error: "Too many requests, slow down." },
});
const publishLimiter = rateLimit({
  windowMs: 60 * 60 * 1000,
  max: 30,                       // 30 publishes/hour per IP
  standardHeaders: true,
  legacyHeaders: false,
  message: { error: "Publish limit reached, try again later." },
});

app.get("/health", (_req, res) => res.json({ ok: true, engine }));

/* GET /sets */
app.get("/sets", (req, res) => {
  const sort = req.query.sort === "new" ? "created_at DESC"
    : req.query.sort === "likes" ? "likes DESC, uses DESC"
    : "uses DESC, likes DESC";
  const lang = clean(req.query.lang, 5);
  const q = clean(req.query.q, 60).toLowerCase();
  let sql = "SELECT * FROM sets WHERE hidden = 0";
  const params = [];
  if (lang === "nl" || lang === "en") { sql += " AND lang = ?"; params.push(lang); }
  if (q) { sql += " AND (lower(name) LIKE ? OR lower(author) LIKE ?)"; params.push("%" + q + "%", "%" + q + "%"); }
  sql += ` ORDER BY ${sort} LIMIT 100`;
  const rows = db.prepare(sql).all(...params);
  const cid = clientOf(req);
  const likedSet = new Set(
    db.prepare("SELECT set_id FROM likes WHERE client_id = ?").all(cid).map((r) => r.set_id)
  );
  res.json(rows.map((r) => rowToPublic(r, likedSet.has(r.id))));
});

/* GET /sets/:id */
app.get("/sets/:id", (req, res) => {
  const row = db.prepare("SELECT * FROM sets WHERE id = ? AND hidden = 0").get(req.params.id);
  if (!row) return res.status(404).json({ error: "Not found" });
  const liked = !!db.prepare("SELECT 1 FROM likes WHERE set_id = ? AND client_id = ?").get(req.params.id, clientOf(req));
  res.json(rowToPublic(row, liked));
});

/* POST /sets  (publish) */
app.post("/sets", writeLimiter, publishLimiter, (req, res) => {
  const body = req.body || {};
  const name = clean(body.name, MAX_NAME_LEN) || "Naamloos";
  const author = clean(body.author, MAX_AUTHOR_LEN) || "Anoniem";
  const lang = body.lang === "en" ? "en" : "nl";
  const code = clean(body.code, MAX_CODE_LEN);
  if (!code.startsWith("KGS1.")) return res.status(400).json({ error: "Invalid code" });

  // de-dup: same code already published? return it instead of a copy.
  const existing = db.prepare("SELECT * FROM sets WHERE code = ? AND hidden = 0").get(code);
  if (existing) return res.json(rowToPublic(existing, false));

  const id = newId();
  const createdAt = new Date().toISOString().slice(0, 10);
  db.prepare(
    "INSERT INTO sets (id, name, author, lang, code, created_at, client_id) VALUES (?, ?, ?, ?, ?, ?, ?)"
  ).run(id, name, author, lang, code, createdAt, clientOf(req));
  const row = db.prepare("SELECT * FROM sets WHERE id = ?").get(id);
  res.status(201).json(rowToPublic(row, false));
});

/* POST /sets/:id/like  (toggle, idempotent per client) */
app.post("/sets/:id/like", writeLimiter, (req, res) => {
  const id = req.params.id;
  const cid = clientOf(req);
  const set = db.prepare("SELECT * FROM sets WHERE id = ? AND hidden = 0").get(id);
  if (!set) return res.status(404).json({ error: "Not found" });
  const has = db.prepare("SELECT 1 FROM likes WHERE set_id = ? AND client_id = ?").get(id, cid);
  const tx = db.transaction(() => {
    if (has) {
      db.prepare("DELETE FROM likes WHERE set_id = ? AND client_id = ?").run(id, cid);
      db.prepare("UPDATE sets SET likes = MAX(0, likes - 1) WHERE id = ?").run(id);
    } else {
      db.prepare("INSERT OR IGNORE INTO likes (set_id, client_id) VALUES (?, ?)").run(id, cid);
      db.prepare("UPDATE sets SET likes = likes + 1 WHERE id = ?").run(id);
    }
  });
  tx();
  const likes = db.prepare("SELECT likes FROM sets WHERE id = ?").get(id).likes;
  res.json({ liked: !has, likes });
});

/* POST /sets/:id/use */
app.post("/sets/:id/use", writeLimiter, (req, res) => {
  const r = db.prepare("UPDATE sets SET uses = uses + 1 WHERE id = ? AND hidden = 0").run(req.params.id);
  if (r.changes === 0) return res.status(404).json({ error: "Not found" });
  const uses = db.prepare("SELECT uses FROM sets WHERE id = ?").get(req.params.id).uses;
  res.json({ uses });
});

/* POST /sets/:id/report  (auto-hide at a threshold) */
app.post("/sets/:id/report", writeLimiter, (req, res) => {
  const id = req.params.id;
  const cid = clientOf(req);
  const set = db.prepare("SELECT * FROM sets WHERE id = ?").get(id);
  if (!set) return res.status(404).json({ error: "Not found" });
  const inserted = db.prepare("INSERT OR IGNORE INTO reports (set_id, client_id) VALUES (?, ?)").run(id, cid);
  if (inserted.changes > 0) {
    db.prepare("UPDATE sets SET reports = reports + 1 WHERE id = ?").run(id);
    // auto-hide once 5 distinct clients report it; review manually in the db.
    db.prepare("UPDATE sets SET hidden = 1 WHERE id = ? AND reports >= 5").run(id);
  }
  res.json({ ok: true });
});

app.get("/ws-health", (_req, res) => res.json({ ok: true, ...roomEngine.stats() }));

/* ---- HTTP polling transport for online play (alternative to /ws) ----
   Same authoritative roomEngine as the WebSocket. A turn-based game doesn't need
   a persistent socket: the client POSTs actions and GETs the state every ~1.5s.
   There's no connection to go half-open, so it can't "miss the last broadcast"
   and freeze — every poll returns the current state. */
const rl = rateLimit({ windowMs: 60 * 1000, max: 600, standardHeaders: true, legacyHeaders: false, message: { error: "Slow down" } });

app.post("/api/room", rl, (req, res) => {
  const b = req.body || {};
  if (!b.playerId) return res.status(400).json({ error: "Missing playerId" });
  const room = roomEngine.create({ hostId: b.playerId, name: b.name, setCode: b.setCode, setName: b.setName, lang: b.lang, alcoholFree: b.alcoholFree, avatar: b.avatar });
  roomEngine.touch(room.code, b.playerId);
  res.json({ code: room.code, hostId: room.hostId, playerId: b.playerId, state: roomEngine.publicState(room) });
});

app.post("/api/room/:code/join", rl, (req, res) => {
  const b = req.body || {};
  if (!b.playerId) return res.status(400).json({ error: "Missing playerId" });
  const r = roomEngine.join({ code: req.params.code, playerId: b.playerId, name: b.name, avatar: b.avatar });
  if (r.error) return res.status(409).json({ error: r.error });
  roomEngine.touch(r.room.code, b.playerId);
  res.json({ code: r.room.code, hostId: r.room.hostId, playerId: b.playerId, state: roomEngine.publicState(r.room) });
});

app.get("/api/room/:code", rl, (req, res) => {
  const pid = req.query.pid ? String(req.query.pid) : null;
  const room = pid ? roomEngine.touch(req.params.code, pid) : roomEngine.get(req.params.code);
  if (!room) return res.status(404).json({ error: "Room niet gevonden" });
  res.json({ code: room.code, hostId: room.hostId, state: roomEngine.publicState(room) });
});

app.post("/api/room/:code/action", rl, (req, res) => {
  const b = req.body || {};
  if (!b.playerId) return res.status(400).json({ error: "Missing playerId" });
  roomEngine.touch(req.params.code, b.playerId);
  const r = roomEngine.action(req.params.code, b.playerId, b.action, b.payload);
  if (r.error) return res.status(409).json({ error: r.error });
  res.json({ code: r.room.code, hostId: r.room.hostId, state: roomEngine.publicState(r.room) });
});

// ---- Entitlements (owned premium decks) keyed by a portable RESTORE CODE ----
// No accounts / no PII: the code IS the credential. Lets purchases survive a
// reinstall + move across devices. NOTE: there's no real payment yet, so the
// client writes its (test-)unlocked decks here; once a payment provider exists
// the GRANT must move server-side (webhook) and the client should only READ.
function makeRestoreCode() {
  const A = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"; // unambiguous (no O/0/I/1)
  let c = ""; for (let i = 0; i < 10; i++) c += A[Math.floor(Math.random() * A.length)];
  return c;
}
app.post("/api/entitlements", rl, (req, res) => {
  const b = req.body || {};
  const decks = Array.isArray(b.decks) ? b.decks.filter((d) => typeof d === "string").slice(0, 50) : [];
  let code = (typeof b.code === "string" && /^[A-Z2-9]{10}$/.test(b.code.toUpperCase())) ? b.code.toUpperCase() : null;
  const now = new Date().toISOString();
  if (!code) { do { code = makeRestoreCode(); } while (db.prepare("SELECT 1 FROM entitlements WHERE code = ?").get(code)); }
  if (db.prepare("SELECT 1 FROM entitlements WHERE code = ?").get(code))
    db.prepare("UPDATE entitlements SET decks = ?, updated_at = ? WHERE code = ?").run(JSON.stringify(decks), now, code);
  else
    db.prepare("INSERT INTO entitlements (code, decks, created_at, updated_at) VALUES (?,?,?,?)").run(code, JSON.stringify(decks), now, now);
  res.json({ code, decks });
});
app.get("/api/entitlements/:code", rl, (req, res) => {
  const code = String(req.params.code || "").toUpperCase();
  const row = db.prepare("SELECT decks FROM entitlements WHERE code = ?").get(code);
  if (!row) return res.status(404).json({ error: "Code niet gevonden" });
  let decks = []; try { decks = JSON.parse(row.decks); } catch { /* */ }
  res.json({ code, decks });
});

