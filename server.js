/* ------------------------------------------------------------------ */
/*  Kingsen community-sets API                                          */
/*  Express + better-sqlite3. Single file, no build step.               */
/*                                                                      */
/*  Endpoints (all JSON):                                               */
/*    GET  /health                  -> { ok: true }                     */
/*    GET  /sets?q=&lang=&sort=      -> [ set, ... ]                     */
/*    GET  /sets/:id                 -> set                             */
/*    POST /sets                     -> set     (publish)               */
/*    POST /sets/:id/like            -> { liked, likes }                */
/*    POST /sets/:id/use             -> { uses }                        */
/*    POST /sets/:id/report          -> { ok }                          */
/*                                                                      */
/*  Client identity comes from the X-Client-Id header (anonymous,       */
/*  generated by the app). Used to make likes idempotent + rate-limit.  */
/* ------------------------------------------------------------------ */
