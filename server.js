/* ---- WebSocket multiplayer on /ws ---- */
const httpServer = createServer(app);
const wss = new WebSocketServer({ server: httpServer, path: "/ws" });

function send(ws, msg) { try { ws.send(JSON.stringify(msg)); } catch { /* closed */ } }
function broadcast(room) {
  const state = roomEngine.publicState(room);
  for (const client of wss.clients) {
    if (client.readyState === 1 && client._code === room.code) {
      send(client, { t: "state", state });
    }
  }
}
// A reconnect (heartbeat re-join from the same player) leaves the OLD socket
// behind. Drop it so there's exactly one live socket per player — otherwise the
// dead socket's late close marks the player offline AFTER they reconnected (and
// would re-arm the host-away grace, closing a room whose host is actually here).
function supersedeOldSockets(ws) {
  for (const c of wss.clients) {
    if (c !== ws && c._code === ws._code && c._pid === ws._pid) {
      c._superseded = true;
      try { c.terminate(); } catch { /* */ }
    }
  }
}
// Is another live socket already serving this player in this room?
function hasLiveSibling(ws) {
  for (const c of wss.clients) {
    if (c !== ws && c.readyState === 1 && c._code === ws._code && c._pid === ws._pid) return true;
  }
  return false;
}

// Relay a voice message to every OTHER voice socket in the same room.
function voiceBroadcast(code, msg, except) {
  for (const c of wss.clients) {
    if (c !== except && c.readyState === 1 && c._vcode === code && c._vpid) send(c, msg);
  }
}

wss.on("connection", (ws) => {
  ws._code = null;
  ws._pid = null;
  ws._vcode = null;   // voice room (separate from the game socket identity)
  ws._vpid = null;
  ws.on("message", (buf) => {
    let m;
    try { m = JSON.parse(String(buf)); } catch { return; }
    if (!m || typeof m.t !== "string") return;

    /* ---- Voice (WebRTC audio) signaling — rides on /ws, independent of game state ---- */
    if (m.t === "voice-join") {
      ws._vcode = String(m.code || "").toUpperCase(); ws._vpid = String(m.pid || "");
      if (!ws._vcode || !ws._vpid) return;
      const peers = [];
      for (const c of wss.clients) if (c !== ws && c.readyState === 1 && c._vcode === ws._vcode && c._vpid) peers.push(c._vpid);
      send(ws, { t: "voice-welcome", peers, iceServers: iceServers() });
      voiceBroadcast(ws._vcode, { t: "voice-peer", pid: ws._vpid }, ws); // tell existing peers a newcomer arrived
      return;
    }
    if (m.t === "voice-signal") {                 // relay an SDP offer/answer or ICE candidate to one peer
      if (!ws._vcode || !ws._vpid) return;
      for (const c of wss.clients) {
        if (c.readyState === 1 && c._vcode === ws._vcode && c._vpid === m.to) { send(c, { t: "voice-signal", from: ws._vpid, data: m.data }); break; }
      }
      return;
    }
    if (m.t === "voice-leave") {
      const code = ws._vcode, pid = ws._vpid; ws._vcode = null; ws._vpid = null;
      if (code && pid) voiceBroadcast(code, { t: "voice-bye", pid }, ws);
      return;
    }

    if (m.t === "create") {
      const room = roomEngine.create({
        hostId: m.playerId, name: m.name, setCode: m.setCode,
        setName: m.setName, lang: m.lang, alcoholFree: m.alcoholFree, avatar: m.avatar,
      });
      ws._code = room.code; ws._pid = m.playerId;
      supersedeOldSockets(ws);
      send(ws, { t: "joined", code: room.code, playerId: m.playerId, hostId: room.hostId });
      broadcast(room);
      return;
    }
    if (m.t === "join") {
      const r = roomEngine.join({ code: m.code, playerId: m.playerId, name: m.name, avatar: m.avatar });
      if (r.error) { send(ws, { t: "error", error: r.error }); return; }
      ws._code = r.room.code; ws._pid = m.playerId;
      supersedeOldSockets(ws);
      send(ws, { t: "joined", code: r.room.code, playerId: m.playerId, hostId: r.room.hostId });
      broadcast(r.room);
      return;
    }
    if (m.t === "action") {
      const r = roomEngine.action(ws._code, ws._pid, m.action, m.payload);
      if (r.error) { send(ws, { t: "error", error: r.error }); return; }
      if (r.room) broadcast(r.room);
      return;
    }
    if (m.t === "ping") { send(ws, { t: "pong" }); return; }
  });
  ws.on("close", () => {
    if (ws._vcode && ws._vpid) { voiceBroadcast(ws._vcode, { t: "voice-bye", pid: ws._vpid }, ws); ws._vcode = null; ws._vpid = null; }
    if (!ws._code || !ws._pid) return;
    // Reconnect-race guard: if a newer live socket already serves this player
    // (they reconnected), this socket was superseded — its close must NOT mark
    // the player offline or re-arm the host-away grace, or a present host's room
    // would wrongly close ~10s later. Only the player's LAST socket disconnects.
    if (ws._superseded || hasLiveSibling(ws)) return;
    const room = roomEngine.disconnect(ws._code, ws._pid);
    if (room) broadcast(room);
  });
});

// Host-grace watchdog: when a host's 10s grace expires, the room closes and we
// push the closed state to everyone still connected so they're notified.
setInterval(() => {
  try {
    const changed = roomEngine.tick();
    for (const room of changed) broadcast(room);
  } catch { /* ignore */ }
}, 1000).unref?.();

httpServer.listen(PORT, () => {
  console.log(`Kingsen server on :${PORT}  (engine: ${engine}, db: ${DB_PATH}, ws: /ws)`);
});
